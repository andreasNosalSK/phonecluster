#!/usr/bin/env bash
# 02_termux_node_setup.sh — Run inside Termux on EVERY phone (Master and Workers).
# Implements Steps 3 & 4 of instruction.txt and configures Termux:Boot auto-start
# for sshd + PhoneCluster worker (and optional Master web dashboard).
set -euo pipefail

NODE_ID=""
IS_MASTER=0
WITH_COMPUTE=0
REPO_DIR="${HOME}/phonecluster"

usage() {
  cat <<'EOF'
Usage: bash scripts/02_termux_node_setup.sh --node-id <node0|node1|...> [options]

Options:
  --node-id <id>   Node ID from config/cluster.json (required, e.g. node0)
  --master         Also auto-start the Master Web Dashboard on boot
  --with-compute   Install optional compiler/HPC tools (clang, cmake, distcc, openmpi, htop)
  --repo-dir <dir> Path where PhoneCluster lives on this phone (default: ~/phonecluster)
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --node-id)
      [[ $# -ge 2 ]] || { echo "Error: --node-id requires a value" >&2; usage; exit 2; }
      NODE_ID="$2"; shift 2 ;;
    --master) IS_MASTER=1; shift ;;
    --with-compute) WITH_COMPUTE=1; shift ;;
    --repo-dir)
      [[ $# -ge 2 ]] || { echo "Error: --repo-dir requires a directory path" >&2; usage; exit 2; }
      REPO_DIR="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "Unknown option: $1" >&2; usage; exit 2 ;;
  esac
done

if [[ -z "${NODE_ID}" ]]; then
  echo "Error: --node-id is required (e.g. --node-id node0)." >&2
  usage
  exit 2
fi

if [[ ! "${NODE_ID}" =~ ^[A-Za-z0-9][A-Za-z0-9._-]{0,39}$ ]]; then
  echo "Error: Invalid --node-id '${NODE_ID}' (must start with alphanumeric and contain only A-Za-z0-9._-, max 40 chars)." >&2
  exit 2
fi

if [[ "${REPO_DIR}" == *$'\n'* || "${REPO_DIR}" == *'"'* || "${REPO_DIR}" == *'$'* || "${REPO_DIR}" == *'`'* || "${REPO_DIR}" == *'\'* ]]; then
  echo "Error: Unsupported special characters in --repo-dir '${REPO_DIR}'." >&2
  exit 2
fi

if [[ "${PREFIX:-}" != *"com.termux"* ]]; then
  echo "Warning: This script is intended for Termux on Android (PREFIX does not look like Termux)." >&2
fi

echo "[1/4] Updating Termux packages and installing core cluster dependencies..."
pkg update -y
pkg upgrade -y
pkg install -y openssh termux-api python jq tmux git

if [[ "${WITH_COMPUTE}" -eq 1 ]]; then
  echo "[1b/4] Installing native ARM64 compute & compiler toolchain..."
  pkg install -y clang cmake make distcc openmpi htop
fi

echo "[2/4] Ensuring SSH daemon (port 8022) is ready..."
mkdir -p "${HOME}/.ssh"
chmod 700 "${HOME}/.ssh"
if [[ ! -s "${HOME}/.ssh/authorized_keys" ]]; then
  if (exec < /dev/tty) 2>/dev/null; then
    echo "Set an SSH password for initial login from your Master phone / PC:"
    passwd < /dev/tty || echo "Warning: passwd did not complete — run 'passwd' manually or pair via 'pc join'." >&2
  else
    echo "Note: Non-interactive shell — run 'passwd' manually in Termux if you need SSH password login." >&2
  fi
fi
pgrep -x sshd >/dev/null 2>&1 || sshd

echo "[3/4] Creating ~/.termux/boot/00-start-cluster.sh for automatic startup on reboot..."
mkdir -p "${HOME}/.termux/boot" "${REPO_DIR}/logs"
BOOT_SCRIPT="${HOME}/.termux/boot/00-start-cluster.sh"

cat > "${BOOT_SCRIPT}" <<EOF
#!/data/data/com.termux/files/usr/bin/sh
# Auto-generated by PhoneCluster 02_termux_node_setup.sh
termux-wake-lock
sshd

REPO_DIR="${REPO_DIR}"
NODE_ID="${NODE_ID}"
LOG_DIR="\${REPO_DIR}/logs"
mkdir -p "\${LOG_DIR}"

if [ -f "\${REPO_DIR}/phonecluster_cli.py" ] && [ -f "\${REPO_DIR}/config/cluster.json" ]; then
  cd "\${REPO_DIR}"
  nohup python3 "\${REPO_DIR}/phonecluster_cli.py" \\
    --config "\${REPO_DIR}/config/cluster.json" \\
    worker --node-id "\${NODE_ID}" \\
    >> "\${LOG_DIR}/worker-\${NODE_ID}.log" 2>&1 < /dev/null &
  echo \$! > "\${LOG_DIR}/worker-\${NODE_ID}.pid"
EOF

if [[ "${IS_MASTER}" -eq 1 ]]; then
  cat >> "${BOOT_SCRIPT}" <<'EOF'

  nohup python3 "${REPO_DIR}/phonecluster_cli.py" \
    --config "${REPO_DIR}/config/cluster.json" \
    dashboard \
    >> "${LOG_DIR}/dashboard.log" 2>&1 < /dev/null &
  echo $! > "${LOG_DIR}/dashboard.pid"
EOF
fi

cat >> "${BOOT_SCRIPT}" <<'EOF'
fi
EOF
chmod 700 "${BOOT_SCRIPT}"

echo "[4/4] Enabling Termux wake lock and verifying battery API..."
termux-wake-lock || true
if command -v termux-battery-status >/dev/null 2>&1; then
  echo "Battery check:"
  timeout 5 termux-battery-status || echo "  (Install Termux:API from the same source as Termux if this timed out)"
fi

LAN_IP="$(ip -4 addr show wlan0 2>/dev/null | awk '/inet /{print $2}' | cut -d/ -f1 | head -n1 || true)"
echo
echo "=== Node '${NODE_ID}' Ready ==="
echo "SSH User : $(whoami)"
echo "LAN IP   : ${LAN_IP:-<check router / ip addr>}"
echo "SSH Cmd  : ssh -p 8022 $(whoami)@${LAN_IP:-<phone-ip>}"
echo "Boot Sh  : ${BOOT_SCRIPT}"
echo "Reminder : Open the Termux:Boot Android app once manually so Android enables boot autostart."
